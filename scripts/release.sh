#!/usr/bin/env bash
#
# release.sh — single, authoritative way to cut a RaptorCode release.
#
# It computes the next semantic version, synchronizes that version across every
# place it lives, builds the Debian installer, then commits, tags, pushes, and
# publishes a GitHub Release with the .deb attached. Running this is the only
# supported way to produce a versioned build, so the package version can never
# drift from the source again.
#
# Version policy (default): auto-derived from Conventional Commit subjects since
# the last vX.Y.Z tag —
#   feat!: / BREAKING CHANGE  -> major
#   feat:                     -> minor
#   anything else (fix/chore/docs/refactor/test/...) -> patch
# Override the policy by passing an explicit level or version as the first arg:
#   ./scripts/release.sh minor
#   ./scripts/release.sh 0.4.0
#
# Flags:
#   --dry-run     compute and print the plan; change nothing.
#   --no-push     commit and tag locally, but do not push or publish.
#   --no-release  push the commit and tag, but do not create a GitHub Release.
#   --skip-tests  skip the cargo test gate (not recommended for real releases).
#
# Synced version surfaces:
#   Cargo.toml (workspace.package.version)  -> binary --version + .deb filename
#   Cargo.lock (regenerated by the build)
#   packaging/dev.raptorlabs.raptorcode.metainfo.xml (new <release> entry)
#   CHANGELOG.md (Unreleased -> vX.Y.Z, fresh Unreleased scaffold)
#   README.md (status line + install filename)
#   git tag vX.Y.Z
#
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

CARGO_TOML="$ROOT_DIR/Cargo.toml"
METAINFO="$ROOT_DIR/packaging/dev.raptorlabs.raptorcode.metainfo.xml"
CHANGELOG="$ROOT_DIR/CHANGELOG.md"
README="$ROOT_DIR/README.md"

AUTHOR_NAME="Bob Vasic"
AUTHOR_EMAIL="17962121+bobvasic@users.noreply.github.com"
# Co-author trailer; override per session with RELEASE_COAUTHOR.
COAUTHOR="${RELEASE_COAUTHOR:-Claude Sonnet 4.6 <noreply@anthropic.com>}"

DRY_RUN=0
DO_PUSH=1
DO_RELEASE=1
RUN_TESTS=1
BUMP_ARG=""

err()  { echo "error: $*" >&2; exit 1; }
info() { echo ">> $*"; }

for arg in "$@"; do
  case "$arg" in
    --dry-run)    DRY_RUN=1 ;;
    --no-push)    DO_PUSH=0 ;;
    --no-release) DO_RELEASE=0 ;;
    --skip-tests) RUN_TESTS=0 ;;
    major|minor|patch) BUMP_ARG="$arg" ;;
    [0-9]*.[0-9]*.[0-9]*) BUMP_ARG="$arg" ;;
    *) err "unknown argument: $arg" ;;
  esac
done

# --- Preflight ---------------------------------------------------------------
command -v cargo    >/dev/null || err "cargo is required"
command -v dpkg-deb >/dev/null || err "dpkg-deb is required"
command -v git      >/dev/null || err "git is required"

if [[ $DRY_RUN -eq 0 && -n "$(git status --porcelain)" ]]; then
  err "working tree is not clean; commit or stash changes before releasing"
fi

# --- Current version ---------------------------------------------------------
CURRENT="$(awk -F' = ' '/^version = / { gsub(/"/, "", $2); print $2; exit }' "$CARGO_TOML")"
[[ -n "$CURRENT" ]] || err "could not read current version from Cargo.toml"
IFS='.' read -r CUR_MAJOR CUR_MINOR CUR_PATCH <<<"$CURRENT"

# --- Determine bump ----------------------------------------------------------
LAST_TAG="$(git describe --tags --abbrev=0 2>/dev/null || true)"
if [[ -n "$LAST_TAG" ]]; then
  RANGE="${LAST_TAG}..HEAD"
  COMMITS="$(git log "$RANGE" --pretty=format:'%s%n%b')"
else
  RANGE="(all history)"
  COMMITS="$(git log --pretty=format:'%s%n%b')"
fi

derive_bump() {
  local subjects breaking feats
  subjects="$(git log ${LAST_TAG:+$LAST_TAG..HEAD} --pretty=format:'%s')"
  breaking="$(echo "$COMMITS" | grep -E '^[a-z]+(\([^)]+\))?!:|BREAKING CHANGE' || true)"
  feats="$(echo "$subjects" | grep -E '^feat(\([^)]+\))?:' || true)"
  if [[ -n "$breaking" ]]; then echo "major";
  elif [[ -n "$feats" ]]; then echo "minor";
  else echo "patch"; fi
}

NEW_VERSION=""
BUMP_KIND=""
if [[ "$BUMP_ARG" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  NEW_VERSION="$BUMP_ARG"
  BUMP_KIND="explicit"
else
  if [[ -n "$BUMP_ARG" ]]; then
    BUMP_KIND="$BUMP_ARG"
  else
    if [[ -z "$COMMITS" ]]; then
      err "no commits since ${LAST_TAG:-repository start}; nothing to release"
    fi
    BUMP_KIND="$(derive_bump)"
  fi
  case "$BUMP_KIND" in
    major) NEW_VERSION="$((CUR_MAJOR + 1)).0.0" ;;
    minor) NEW_VERSION="${CUR_MAJOR}.$((CUR_MINOR + 1)).0" ;;
    patch) NEW_VERSION="${CUR_MAJOR}.${CUR_MINOR}.$((CUR_PATCH + 1))" ;;
  esac
fi

# Guard: new version must be strictly greater than current.
LOWEST="$(printf '%s\n%s\n' "$CURRENT" "$NEW_VERSION" | sort -V | head -1)"
if [[ "$NEW_VERSION" == "$CURRENT" || "$LOWEST" == "$NEW_VERSION" ]]; then
  err "new version $NEW_VERSION is not greater than current $CURRENT"
fi

TAG="v${NEW_VERSION}"
DATE="$(date +%Y-%m-%d)"
ARCH="$(dpkg --print-architecture)"
DEB="dist/raptor-code_${NEW_VERSION}_${ARCH}.deb"

# --- Plan summary ------------------------------------------------------------
echo "----------------------------------------------------------------------"
echo " RaptorCode release plan"
echo "----------------------------------------------------------------------"
echo "  current version : $CURRENT"
echo "  bump            : $BUMP_KIND"
echo "  new version     : $NEW_VERSION  (tag $TAG, $DATE)"
echo "  last tag        : ${LAST_TAG:-<none>}"
echo "  commit range    : $RANGE"
echo "  artifact        : $DEB"
echo "  push            : $([[ $DO_PUSH -eq 1 ]] && echo yes || echo no)"
echo "  github release  : $([[ $DO_RELEASE -eq 1 ]] && echo yes || echo no)"
echo "  run tests       : $([[ $RUN_TESTS -eq 1 ]] && echo yes || echo no)"
echo "----------------------------------------------------------------------"

if [[ $DRY_RUN -eq 1 ]]; then
  info "dry run — no files changed, nothing built, no git actions taken."
  exit 0
fi

# --- Quality gate ------------------------------------------------------------
if [[ $RUN_TESTS -eq 1 ]]; then
  info "running test gate (cargo test --workspace)"
  cargo test --workspace
fi

# --- Sync version surfaces ---------------------------------------------------
info "updating Cargo.toml -> $NEW_VERSION"
sed -i "s/^version = \"${CURRENT}\"/version = \"${NEW_VERSION}\"/" "$CARGO_TOML"

info "inserting metainfo.xml <release> entry"
awk -v ver="$NEW_VERSION" -v date="$DATE" '
  /<releases>/ {
    print
    print "    <release version=\"" ver "\" date=\"" date "\">"
    print "      <description>"
    print "        <p>See CHANGELOG.md for the changes in this release.</p>"
    print "      </description>"
    print "    </release>"
    next
  }
  { print }
' "$METAINFO" >"$METAINFO.tmp" && mv "$METAINFO.tmp" "$METAINFO"

info "rolling CHANGELOG.md Unreleased -> $TAG"
awk -v ver="$NEW_VERSION" -v date="$DATE" '
  !done && $0 == "## Unreleased" {
    print "## Unreleased"
    print ""
    print "## v" ver " - " date
    done = 1
    next
  }
  { print }
' "$CHANGELOG" >"$CHANGELOG.tmp" && mv "$CHANGELOG.tmp" "$CHANGELOG"

info "updating README.md version references"
sed -i \
  -e "s/Current status: v${CURRENT}\b/Current status: v${NEW_VERSION}/" \
  -e "s/raptor-code_${CURRENT}_amd64\.deb/raptor-code_${NEW_VERSION}_amd64.deb/g" \
  "$README"

# --- Build the installer (also regenerates Cargo.lock for the new version) ---
info "building Debian installer"
RAPTOR_VERSION="$NEW_VERSION" ./scripts/package-deb.sh >/dev/null
[[ -f "$DEB" ]] || err "expected artifact not produced: $DEB"
info "built $DEB"

# --- Commit, tag, push -------------------------------------------------------
git config user.name  "$AUTHOR_NAME"
git config user.email "$AUTHOR_EMAIL"

git add "$CARGO_TOML" "$ROOT_DIR/Cargo.lock" "$METAINFO" "$CHANGELOG" "$README"
git commit -m "release: ${TAG}" -m "Co-Authored-By: ${COAUTHOR}"
git tag -a "$TAG" -m "RaptorCode ${TAG}"
info "committed and tagged $TAG locally"

if [[ $DO_PUSH -eq 0 ]]; then
  info "skipping push (--no-push). To publish: git push origin HEAD && git push origin $TAG"
  exit 0
fi

info "pushing commit and tag to origin"
git push origin HEAD
git push origin "$TAG"

# --- GitHub Release ----------------------------------------------------------
if [[ $DO_RELEASE -eq 0 ]]; then
  info "skipping GitHub release (--no-release). Artifact ready at $DEB"
  exit 0
fi

if command -v gh >/dev/null && gh auth status >/dev/null 2>&1; then
  info "creating GitHub release $TAG with $DEB"
  gh release create "$TAG" "$DEB" \
    --title "RaptorCode ${TAG}" \
    --notes "See CHANGELOG.md for the changes in ${TAG}."
  info "release published: $TAG"
else
  info "gh unavailable or unauthenticated; skipped GitHub release."
  info "publish manually: gh release create $TAG $DEB --title 'RaptorCode $TAG'"
fi

info "done."
