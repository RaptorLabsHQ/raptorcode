    #[test]
    fn rejects_unsafe_task_ids() {
        for id in ["", "../secret", "Unsafe", "-task", "task-", "task_1"] {
            let error = TaskId::parse(id).unwrap_err();

            assert_eq!(error, TaskError::UnsafeId(id.to_owned()));
            assert_eq!(error.to_string(), format!("task id is not safe: {id}"));
        }
    }

    #[test]
    fn escapes_and_unescapes_kv_strings() {
        let raw = "quote \" slash \\ newline\n return\r tab\t plain";
        let escaped = escape_kv_string(raw);

        assert_eq!(
            escaped,
            "quote \\\" slash \\\\ newline\\n return\\r tab\\t plain"
        );
        assert_eq!(unescape_kv_string(&escaped).unwrap(), raw);
        assert_eq!(escape_kv_string("plain"), "plain");
        assert_eq!(unescape_kv_string("plain").unwrap(), "plain");
        assert_eq!(escape_kv_string(""), "");
        assert_eq!(unescape_kv_string("").unwrap(), "");
    }

    #[test]
    fn rejects_malformed_kv_escapes() {
        assert_eq!(
            unescape_kv_string("trailing\\").unwrap_err(),
            KvUnescapeError::IncompleteEscape
        );
        assert_eq!(
            unescape_kv_string("bad \\x escape").unwrap_err(),
            KvUnescapeError::UnsupportedEscape
        );
        assert_eq!(
            KvUnescapeError::IncompleteEscape.to_string(),
            "has an incomplete escape sequence"
        );
        assert_eq!(
            KvUnescapeError::UnsupportedEscape.to_string(),
            "has an unsupported escape sequence"
        );
    }
