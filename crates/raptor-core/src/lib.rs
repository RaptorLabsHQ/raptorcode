    #[test]
    fn stable_hash_hex_is_deterministic_fnv1a() {
        // FNV-1a 64-bit reference vectors: the offset basis for the empty
        // string, and the published value for "a".
        assert_eq!(stable_hash_hex(""), "cbf29ce484222325");
        assert_eq!(stable_hash_hex("a"), "af63dc4c8601ec8c");
        assert_eq!(stable_hash_hex("RaptorCode"), stable_hash_hex("RaptorCode"));
        assert_ne!(stable_hash_hex("a"), stable_hash_hex("b"));
        assert_eq!(stable_hash_hex("anything").len(), 16);
        assert!(stable_hash_hex("anything")
            .chars()
            .all(|character| character.is_ascii_hexdigit() && !character.is_ascii_uppercase()));
    }

